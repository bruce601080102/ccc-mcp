"""Build the three comparison cases for the P0B user-study materials.

Each case is the SAME three-Task history (TASK-0001 committed, TASK-0002 committed,
TASK-0003 uncommitted with out-of-plan, pending and excluded items), generated by the
same fixture generator with only the domain words replaced. Structure is identical;
only the surface topic differs. Nothing here calls a model or touches the ccc-mcp
working tree: demo repositories are built under the directory given on the command line,
which must be outside the ccc-mcp checkout.

Usage:
  python build_cases.py <scratch-dir>          # builds raw repos + pipeline outputs
  python build_cases.py <scratch-dir> --facts  # also writes fact sheets to this folder
"""

import json
import sys
import types
from pathlib import Path

HERE = Path(__file__).resolve().parent
ARCH = HERE.parent
CCC_ROOT = HERE.parents[2]  # ccc-mcp checkout root
NOTES = ARCH / "fixtures" / "notes_cli"
sys.path.insert(0, str(ARCH))

from archgraph.pipeline import run_pipeline  # noqa: E402

# Word replacements applied to the fixture source, its plans and its confirmations.
# Order matters: longer / more specific tokens first.
CASES = {
    "case1_notes": [],
    "case2_bookmarks": [
        ("NotesStore", "BookmarkStore"),
        ("Notes", "Bookmarks"),
        ("notes", "bookmarks"),
        ("Note", "Bookmark"),
        ("note", "bookmark"),
        ("筆記", "書籤"),
    ],
    "case3_todos": [
        ("NotesStore", "TodoStore"),
        ("Notes", "Todos"),
        ("notes", "todos"),
        ("Note", "Todo"),
        ("note", "todo"),
        ("筆記", "待辦"),
    ],
}
TEST_ARGV = [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider"]


def transform(text, pairs):
    for old, new in pairs:
        text = text.replace(old, new)
    return text


def load_variant(case_id, pairs):
    """Execute the fixture generator with replaced words. The checkout-root guard is
    pointed at a path that can never contain the scratch demo, so the guard stays active
    for the real ccc-mcp checkout while the scratch build is allowed."""
    source = transform((NOTES / "make_notes_cli.py").read_text(encoding="utf-8"), pairs)
    # The fixture's own guard points at the notes_cli location; repoint it at the real
    # ccc-mcp checkout so building inside the checkout is still refused.
    source = source.replace(
        "ROOT = Path(__file__).resolve().parents[3]  # ccc-mcp checkout root",
        f"ROOT = Path({str(CCC_ROOT)!r})",
    )
    assert f"ROOT = Path({str(CCC_ROOT)!r})" in source, "fixture guard line changed"
    module = types.ModuleType(f"variant_{case_id}")
    module.__file__ = str(NOTES / "make_notes_cli.py")
    exec(compile(source, module.__file__, "exec"), module.__dict__)
    return module


def _arch(out, task):
    return json.loads((out / task / "architecture.json").read_text(encoding="utf-8"))


def run_case(case_id, out_root):
    pairs = CASES[case_id]
    out = Path(out_root) / case_id
    out.mkdir(parents=True, exist_ok=True)
    module = load_variant(case_id, pairs)
    refs = module.build(out / "repo")
    plans = out / "plans"
    plans.mkdir(exist_ok=True)
    plan_files = {}
    for name in ("plan1", "plan2", "plan3"):
        raw = (NOTES / "plans" / f"{name}.json").read_text(encoding="utf-8")
        target = plans / f"{name}.json"
        target.write_text(transform(raw, pairs), encoding="utf-8")
        plan_files[name] = target
    confirmations = json.loads(
        transform((NOTES / "confirmations3.json").read_text(encoding="utf-8"), pairs)
    )
    db = out / "archgraph.sqlite"
    c1, c2 = f"commit:{refs['C1']}", f"commit:{refs['C2']}"
    results = {
        "TASK-0001": run_pipeline(
            out / "repo", ["empty", c1], db, out / "TASK-0001",
            plan_source=plan_files["plan1"], test_argv=TEST_ARGV,
        ),
        "TASK-0002": run_pipeline(
            out / "repo", [c1, c2], db, out / "TASK-0002",
            plan_source=plan_files["plan2"], test_argv=TEST_ARGV,
            prior_architectures=[_arch(out, "TASK-0001")],
        ),
        "TASK-0003": run_pipeline(
            out / "repo", [c1, c2, "worktree"], db, out / "TASK-0003",
            plan_source=plan_files["plan3"], confirmations=confirmations, test_argv=TEST_ARGV,
            prior_architectures=[_arch(out, "TASK-0001"), _arch(out, "TASK-0002")],
        ),
    }
    (out / "results.json").write_text(
        json.dumps(results, ensure_ascii=False, indent=2, default=str), encoding="utf-8"
    )
    return out, results


if __name__ == "__main__":
    scratch = Path(sys.argv[1]).resolve()
    scratch.mkdir(parents=True, exist_ok=True)
    summary = {}
    for case_id in CASES:
        out, results = run_case(case_id, scratch)
        summary[case_id] = {
            task: {k: results[task].get(k) for k in ("commit_state", "structure_state", "host_test_state")}
            for task in results
        }
    print(json.dumps(summary, ensure_ascii=False, indent=2))
